let currentLocale: 'en' | 'de' =
  Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase().startsWith('de') ? 'de' : 'en'

function interpolate(template: string, variables?: Variables): string {
  if (!variables) return template
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    variables[name] === undefined ? `{${name}}` : String(variables[name])
  )
}

export function t(key: TranslationKey, variables?: Variables): string {
  const catalog = currentLocale === 'de' ? de : en
  return interpolate(catalog[key], variables)
}

export function formatNumber(value: number): string {
  return new Intl.NumberFormat(currentLocale).format(value)
}

export function formatDecimal(value: number, maximumFractionDigits = 1): string {
  return new Intl.NumberFormat(currentLocale, { maximumFractionDigits }).format(value)
}

export function vpnStatusLabel(status: string | undefined): string {
  switch (status) {
    case 'connected':
      return t('common.connected')
    case 'connecting':
      return t('common.connecting')
    case 'disconnected':
      return t('common.disconnected')
    case 'disabled':
      return t('common.disabled')
    case 'error':
      return t('common.error')
    default:
      return status || t('servers.unknown')
  }
}

export function setLocaleForTesting(locale: 'en' | 'de'): void {
  currentLocale = locale
}
